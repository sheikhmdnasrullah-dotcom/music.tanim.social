function withTimings(raw: Song): Song {
  const byId = new Map(raw.sections.map((s) => [s.id, s] as const));
  const ordered: SongSection[] = [];
  for (const id of SECTION_ORDER) {
    const section = byId.get(id);
    if (section) ordered.push(section);
  }
  for (const section of raw.sections) {
    if (!SECTION_ORDER.includes(section.id as (typeof SECTION_ORDER)[number])) {
      ordered.push(section);
    }
  }

  let offset = 0;
  const sections = ordered.map((section) => {
    const timing = SECTION_TIMINGS[section.id];
    if (!timing) return section;

    const lines = section.lines.map((line, i) => {
      const lt = timing.lines[i];
      if (!lt) return line;
      return {
        ...line,
        startTime: lt.start,
        duration: lt.end - lt.start,
        syllables: line.syllables.map((syllable, j) => {
          const st = lt.syllables[j];
          if (!st) return syllable;
          return { ...syllable, startTime: st.start, duration: st.end - st.start };
        }),
      };
    });

    const startTime = offset;
    offset += timing.duration;
    return { ...section, lines, startTime, duration: timing.duration };
  });

  return { ...raw, sections, totalDuration: offset };
}

